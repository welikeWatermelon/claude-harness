      return [{ line: 1, msg: `ErrorCode ${gone.join(', ')} 를 삭제/이름 변경해요. 프론트가 이 코드로 분기하면 깨져요:\n${lines.join('\n')}\n    → 이름 변경이면 프론트도 같이 고치고 docs/api/API_CHANGES.md 에 기록하세요.` }];
