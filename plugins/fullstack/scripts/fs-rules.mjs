/** 첫 10줄의 주석에 생성 표시가 있는지 */
export function hasGeneratedHeader(text) {
  if (!text) return false;
  return text
    .split(/\r?\n/)
    .slice(0, 10)
    .some((l) => /^\s*(\/\/|\/\*|\*|#|<!--)/.test(l) && GENERATED_MARK.test(l));
}
